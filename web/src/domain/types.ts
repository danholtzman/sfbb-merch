export type Id = string;
export type Side = "front" | "back";
export type Role = "member" | "admin";
export type Progress = "OPEN" | "DELIVERED_UNPAID" | "COMPLETE";
export type Lifecycle = "DRAFT" | "PUBLISHED" | "ARCHIVED";
export type PlacementValues = { x: number; y: number; width: number; rotation: number };
export type Actor = { role: Role; sessionId: Id };
export type RequestContext = { actor: Actor; now: Date };
export type ServiceResult<T> = Promise<T>;
export type OrderLineInput = { styleId: Id; artworkSetId: Id; colorId: Id; sizeId: Id; quantity: number };
export type AdminOrderLineInput = OrderLineInput & { unitPriceCents: number; originalLineId?: Id };
export type OrderLineView = OrderLineInput & { id: Id; unitPriceCents: number; styleName: string; artworkSetName: string; colorName: string; colorHex: string; sizeLabel: string };
export type OrderView = { id: Id; code: string; seasonId: Id; fullName: string; note: string; progress: Progress; cancelled: boolean; version: number; lines: OrderLineView[]; amountOwedCents: number };
export type ColorView = { id: Id; name: string; hex: string; position: number };
export type SizeView = { id: Id; label: string; position: number };
export type StyleView = { id: Id; seasonId: Id; name: string; description: string; manufacturerUrl: string; unitPriceCents: number; cut: "classic" | "fitted" | "long"; version: number; colors: ColorView[]; sizes: SizeView[]; artworkSetIds: Id[]; backPhotoColorIds?: Id[] };
export type ArtworkSetView = { id: Id; seasonId: Id; name: string; frontAssetId: Id | null; backAssetId: Id | null; version: number };
export type SeasonView = { id: Id; name: string; opensOn: string; closesOn: string; announcement: string; lifecycle: Lifecycle; version: number };
export type AssetView = { id: Id; url: string; mime: "image/png" | "image/jpeg"; width: number; height: number; byteSize: number };
