import { test, expect } from "@playwright/test";
import sharp from "sharp";
import credentials from "../fixtures/credentials.json" with { type: "json" };
test("paired uploads and color-specific blanks persist through reload, and new sets can be deleted", async ({ page, isMobile }, info) => {
 test.skip(isMobile, "Artwork administration is desktop only.");
 await page.goto("/login");
 await page.getByLabel("Username", { exact: true }).fill("admin");
 await page.getByLabel("Password", { exact: true }).fill(credentials.adminPassword);
 await page.getByRole("button", { name: /Sign in/ }).click();
 await expect(page).toHaveURL(/\/admin$/);
 const session = (await (await page.request.get("/api/auth/session")).json()).data;
 const headers = { Origin: "http://127.0.0.1:3100", "X-CSRF-Token": session.csrfToken };
 const firstSeason = (await (await page.request.get("/api/admin/seasons")).json()).data[0];
 const created = await page.request.post("/api/admin/seasons", { headers, data: { name: "Artwork browser season", opensOn: "2027-04-01", closesOn: "2027-04-30", announcement: "", copyFromSeasonId: firstSeason.id, reuseArtwork: true } });
 expect(created.ok()).toBe(true);
 const copy = (await created.json()).data;
 await page.reload();
 await page.getByLabel("Switch season").selectOption(copy.id);
 await page.getByRole("tab", { name: "Merchandise", exact: true }).click();
 await page.getByRole("button", { name: "Manage artwork", exact: true }).click();
 const dialog = page.getByRole("dialog");
 const png = await sharp({ create: { width: 30, height: 50, channels: 4, background: { r: 200, g: 10, b: 80, alpha: .5 } } }).png().toBuffer();
 await dialog.getByRole("combobox", { name: "Artwork set", exact: true }).selectOption({ label: "Season artwork" });
 await dialog.getByLabel("Upload front artwork").setInputFiles({ name: "front.png", mimeType: "image/png", buffer: png });
 await expect(dialog.getByRole("img", { name: "Front artwork preview" })).toBeVisible();
 await expect.poll(() => dialog.getByRole("img", { name: "Front artwork preview" }).evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(30);
 await dialog.getByLabel("Upload back artwork").setInputFiles({ name: "back.png", mimeType: "image/png", buffer: png });
 await expect(dialog.getByRole("img", { name: "Back artwork preview" })).toBeVisible();
 await expect.poll(() => dialog.getByRole("img", { name: "Back artwork preview" }).evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(30);
 await page.screenshot({ path: info.outputPath("artwork-slots.png"), fullPage: true });
 await dialog.getByRole("button",{name:"Remove front artwork",exact:true}).click();
 await expect(dialog.getByRole("img",{name:"Front artwork preview"})).toHaveCount(0);
 await expect(dialog.getByRole("img",{name:"Back artwork preview"})).toBeVisible();
 await dialog.getByRole("button",{name:"Remove back artwork",exact:true}).click();
 await expect(dialog.getByRole("img",{name:"Back artwork preview"})).toHaveCount(0);
 for(const side of ["front","back"]) {await dialog.getByLabel(`Upload ${side} artwork`).setInputFiles({name:`${side}.png`,mimeType:"image/png",buffer:png});await expect(dialog.getByRole("img",{name:`${side === "front" ? "Front" : "Back"} artwork preview`})).toBeVisible();}
 await dialog.getByRole("button", { name: "Done", exact: true }).click();
 const first = page.getByRole("article").first();
 await expect(first.locator('svg image[data-artwork="true"]')).toHaveCount(1);
 await expect(first.getByRole("button",{name:"Edit back preview for Browser test tee",exact:true})).toHaveCount(0);
 await first.getByRole("button", { name: "Manage style", exact: true }).click();
 await dialog.getByLabel("Upload blank front photo").setInputFiles({ name: "blank.png", mimeType: "image/png", buffer: png });
 await expect(dialog.getByText("Front blank photo saved", { exact: true })).toBeVisible();
 await dialog.getByLabel("Upload blank back photo").setInputFiles({name:"back-shirt.png",mimeType:"image/png",buffer:png});
 await expect(dialog.getByText("Back blank photo saved",{exact:true})).toBeVisible();
 await dialog.getByRole("button", { name: "Done", exact: true }).click();
 await page.reload();
 await page.getByLabel("Switch season").selectOption(copy.id);
 await page.getByRole("tab", { name: "Merchandise", exact: true }).click();
 await expect(first.locator('svg image[data-blank="true"]')).toHaveCount(2);
 await expect(first.getByRole("button",{name:"Edit back preview for Browser test tee",exact:true})).toBeVisible();
 await page.getByRole("button", { name: "Manage artwork", exact: true }).click();
 await dialog.getByText("Additional artwork sets (optional)", { exact: true }).click();
 await dialog.getByLabel("New set name").fill("Browser additional set");
 await dialog.getByRole("button", { name: "Add artwork set", exact: true }).click();
 await expect(dialog.getByRole("combobox", { name: "Artwork set", exact: true })).toHaveValue(/.+/);
 await expect(dialog.getByText("Front artwork not uploaded", { exact: true })).toBeVisible();
 await dialog.getByRole("button", { name: "Delete artwork set", exact: true }).click();
 await expect(dialog.getByRole("heading")).toHaveText("Delete Browser additional set?");
 await dialog.getByRole("button", { name: "Yes, delete artwork set", exact: true }).click();
 await expect(dialog.getByRole("combobox", { name: "Artwork set", exact: true }).getByRole("option", { name: "Browser additional set" })).toHaveCount(0);
 await dialog.getByRole("button", { name: "Done", exact: true }).click();
 const current = (await (await page.request.get("/api/admin/seasons")).json()).data.find((s: { id: string }) => s.id === copy.id);
 expect((await page.request.delete(`/api/admin/seasons/${copy.id}`, { headers, data: { expectedVersion: current.version } })).ok()).toBe(true);
});
