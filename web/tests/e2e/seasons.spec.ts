test("dragging across the curtain keeps the modal open; Escape restores focus", async ({ page }) => {
  const manage = page.getByRole("article").first().getByRole("button", { name: "Manage", exact: true });
  await manage.click();
  const dialog = page.getByRole("dialog");
  await page.mouse.move(5, 5); await page.mouse.down();
  await page.mouse.move(100, 5); await page.mouse.up();
  await expect(dialog).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(manage).toBeFocused();
});
