import { expect, test } from "@playwright/test";
import credentials from "../fixtures/credentials.json" with { type: "json" };
test.beforeEach(async ({ page, isMobile }) => {
  test.skip(isMobile, "Season administration is desktop only.");
  await page.goto("/login");
  await page.getByLabel("Username", { exact: true }).fill("admin");
  await page.getByLabel("Password", { exact: true }).fill(credentials.adminPassword);
  await page.getByRole("button", { name: /Sign in/ }).click();
  await expect(page).toHaveURL(/\/admin$/);
  await page.getByRole("tab", { name: "Seasons", exact: true }).click();
});
test("creates a draft, edits only in a modal, and deletes through named confirmation", async ({ page }, info) => {
  await expect(page.getByText("Selected season", { exact: true })).toBeHidden();
  await page.getByRole("button", { name: "+ New season" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Season name", { exact: true }).fill("Spring browser test");
  await dialog.getByLabel("Opens on").fill("2027-03-01");
  await dialog.getByLabel("Closes on").fill("2027-03-31");
  await dialog.getByRole("button", { name: "Create season" }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("tab", { name: "Merchandise", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(page.getByTestId("season-context")).toContainText("Spring browser test");
  await page.getByRole("tab", { name: "Seasons", exact: true }).click();
  const card = page.getByRole("article").filter({ has: page.getByRole("heading", { name: "Spring browser test", exact: true }) });
  await card.getByRole("button", { name: "Publish season" }).click();
  await expect(page.locator(".admin-dashboard").getByRole("alert")).toContainText("Add at least one shirt style");
  await card.getByRole("button", { name: "Manage", exact: true }).click();
  await dialog.getByLabel("Season name", { exact: true }).fill("Spring revised");
  await dialog.getByRole("button", { name: "Save season" }).click();
  const revised = page.getByRole("article").filter({ has: page.getByRole("heading", { name: "Spring revised", exact: true }) });
  await expect(revised).toBeVisible();
  await revised.getByRole("button", { name: "Manage", exact: true }).click();
  await dialog.getByLabel("Season name", { exact: true }).fill("Unsaved edit");
  await dialog.getByRole("button", { name: "Delete season", exact: true }).click();
  await expect(dialog.getByRole("heading")).toHaveText("Delete Spring revised?");
  await dialog.getByRole("button", { name: "Keep season" }).click();
  await expect(dialog.getByLabel("Season name", { exact: true })).toHaveValue("Unsaved edit");
  await page.screenshot({ path: info.outputPath("season-settings.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Delete season", exact: true }).click();
  await dialog.getByRole("button", { name: "Yes, delete season" }).click();
  await expect(dialog).toHaveCount(0);
  await expect(revised).toHaveCount(0);
  await expect(page.getByRole("tab", { name: "Seasons", exact: true })).toHaveAttribute("aria-selected", "true");
});
test("cancel discards changes, drag release outside keeps modal open, last season is protected", async ({ page }) => {
  const card = page.getByRole("article").first();
  await card.getByRole("button", { name: "Manage", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Season name", { exact: true }).fill("Discard this");
  const box = await dialog.getByLabel("Season name", { exact: true }).boundingBox();
  await page.mouse.move(box!.x + 20, box!.y + 20); await page.mouse.down();
  await page.mouse.move(5, 5); await page.mouse.up();
  await expect(dialog).toBeVisible();
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  await card.getByRole("button", { name: "Manage", exact: true }).click();
  await expect(dialog.getByLabel("Season name", { exact: true })).not.toHaveValue("Discard this");
  await dialog.getByRole("button", { name: "Delete season", exact: true }).click();
  await dialog.getByRole("button", { name: "Yes, delete season" }).click();
  await expect(dialog.getByRole("alert")).toContainText("last season cannot be deleted");
  await dialog.getByRole("button", { name: "Keep season" }).click();
  await page.mouse.click(5, 5);
  await expect(dialog).toHaveCount(0);
});
test("season endpoints reject forged roles, missing CSRF, and invalid input", async ({ page }) => {
  expect((await page.request.post("/api/admin/seasons", { data: {}, headers: { Origin: "http://127.0.0.1:3100" } })).status()).toBe(403);
  const session = (await (await page.request.get("/api/auth/session")).json()).data;
  const headers = { Origin: "http://127.0.0.1:3100", "X-CSRF-Token": session.csrfToken };
  expect((await page.request.post("/api/admin/seasons", { data: { name: "Bad dates", opensOn: "2027-03-31", closesOn: "2027-03-01", announcement: "", copyFromSeasonId: null, reuseArtwork: false }, headers })).status()).toBe(422);
  await page.getByRole("button", { name: "Sign out" }).click();
  await expect(page).toHaveURL(/\/login$/);
  expect((await page.request.get("/api/admin/seasons")).status()).toBe(401);
  await page.getByLabel("Username", { exact: true }).fill("user");
  await page.getByLabel("Password", { exact: true }).fill(credentials.memberPassword);
  await page.getByRole("button", { name: /Sign in/ }).click();
  await expect(page).toHaveURL(/\/shop$/);
  expect((await page.request.get("/api/admin/seasons", { headers: { "X-Role": "admin" } })).status()).toBe(403);
});

