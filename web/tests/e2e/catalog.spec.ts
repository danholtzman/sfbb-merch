test("catalog routes enforce CSRF, versions, and administrator identity", async ({ page }) => {
 const session = (await (await page.request.get("/api/auth/session")).json()).data;
 const seasons = (await (await page.request.get("/api/admin/seasons")).json()).data;
 const catalogUrl = `/api/admin/seasons/${seasons[0].id}/catalog`;
 const catalog = (await (await page.request.get(catalogUrl)).json()).data;
 const style = catalog.styles[0];
 const url = `/api/admin/styles/${style.id}/price`;
 expect((await page.request.patch(url, { headers: { Origin: "http://127.0.0.1:3100" }, data: { expectedVersion: style.version, unitPriceCents: 1 } })).status()).toBe(403);
 const headers = { Origin: "http://127.0.0.1:3100", "X-CSRF-Token": session.csrfToken };
 expect((await page.request.patch(url, { headers, data: { expectedVersion: style.version, unitPriceCents: 1.5 } })).status()).toBe(422);
 expect((await page.request.patch(url, { headers, data: { expectedVersion: style.version + 1, unitPriceCents: 1 } })).status()).toBe(409);
 await page.getByRole("button", { name: "Sign out" }).click();
 await expect(page).toHaveURL(/\/login$/);
 expect((await page.request.get(catalogUrl)).status()).toBe(401);
 await page.getByLabel("Username", { exact: true }).fill("user");
 await page.getByLabel("Password", { exact: true }).fill(credentials.memberPassword);
 await page.getByRole("button", { name: /Sign in/ }).click();
 await expect(page).toHaveURL(/\/shop$/);
 expect((await page.request.get(catalogUrl, { headers: { "X-Role": "admin" } })).status()).toBe(403);
});
